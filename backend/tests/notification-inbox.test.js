'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {randomBytes}=require('node:crypto');
process.env.PG_SCHEMA='mk_notify_'+randomBytes(6).toString('hex');
process.env.HOST='127.0.0.1';
const {server,ready,pool}=require('../server');
const shift=days=>{
 const p=new Intl.DateTimeFormat('en-US',{timeZone:'Asia/Manila',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(new Date());
 const d=Object.fromEntries(p.map(x=>[x.type,x.value]));
 const dt=new Date(d.year+'-'+d.month+'-'+d.day+'T12:00:00Z');
 dt.setUTCDate(dt.getUTCDate()+days);return dt.toISOString().slice(0,10);
};
let base;
async function call(method,url,body,cookie){
 const response=await fetch(base+url,{method,headers:{
  ...(cookie?{cookie}:{}),
  ...(body===undefined?{}:{'content-type':'application/json'}),
  'x-motokare-client':'web'
 },...(body===undefined?{}:{body:JSON.stringify(body)})});
 return {status:response.status,data:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0]};
}
test('Phase 4.6: notification inbox persists per account, tracks read state and never shares other users\' events',async t=>{
 await ready;
 await new Promise(done=>server.listen(0,'127.0.0.1',done));
 base='http://127.0.0.1:'+server.address().port;
 t.after(async()=>{
  await new Promise(done=>server.close(done));
  await pool.query('DROP SCHEMA IF EXISTS "'+process.env.PG_SCHEMA+'" CASCADE');
  await pool.end();
 });
 const register=(role,fullName,email,shopName)=>call('POST','/api/auth/register',{
  role,fullName,email,password:'aStrongSecurePassword1234!',...(shopName?{shopName}:{})
 });
 const r1=await register('rider','Rider Alpha','notify-r1@demo.test');
 const r2=await register('rider','Rider Beta','notify-r2@demo.test');
 const shop=await register('shop','Workshop Owner','notify-shop1@demo.test','Inbox Moto Garage');
 const otherShop=await register('shop','Another Owner','notify-shop2@demo.test','Other Moto Shop');
 for(const r of [r1,r2,shop,otherShop])assert.equal(r.status,201,JSON.stringify(r.data));
 const rider=r1.cookie,other=r2.cookie,workshop=shop.cookie,shop2=otherShop.cookie,shopId=shop.data.user.id;
 const inbox=cookie=>call('GET','/api/notification-inbox',undefined,cookie);
 assert.equal((await inbox()).status,401);
 assert.equal((await call('POST','/api/notification-inbox/read-all',{},undefined)).status,401);
 assert.equal((await inbox(rider)).data.unreadCount,0);
 assert.equal((await inbox(workshop)).data.unreadCount,0);
 const bike=await call('POST','/api/bikes',{model:'Honda Beat',year:2025},rider);
 assert.equal(bike.status,201);
 const req=await call('POST','/api/connections',{shopId},rider);
 assert.equal(req.status,201);
 let shopEvents=(await inbox(workshop)).data;
 assert.equal(shopEvents.unreadCount,1);
 assert.equal(shopEvents.notifications.length,1);
 const connectionEvent=shopEvents.notifications[0];
 assert.equal(connectionEvent.type,'connection-request');
 assert.equal(connectionEvent.route,'/shop/connections');
 assert.equal(connectionEvent.readAt,null);
 assert.equal((await inbox(other)).data.unreadCount,0);
 assert.equal((await inbox(shop2)).data.notifications.length,0);
 assert.equal((await call('PATCH','/api/notification-inbox/'+connectionEvent.id,{read:true},rider)).status,404);
 assert.equal((await call('DELETE','/api/notification-inbox/'+connectionEvent.id,undefined,shop2)).status,404);
 assert.equal((await call('PATCH','/api/notification-inbox/'+connectionEvent.id,{read:'yes'},workshop)).status,400);
 assert.equal((await call('PATCH','/api/notification-inbox/'+connectionEvent.id,{read:true},workshop)).status,200);
 assert.equal((await inbox(workshop)).data.unreadCount,0);
 assert.ok((await inbox(workshop)).data.notifications[0].readAt);
 assert.equal((await call('PATCH','/api/notification-inbox/'+connectionEvent.id,{read:false},workshop)).status,200);
 assert.equal((await inbox(workshop)).data.unreadCount,1);
 const bootstrap=(await call('GET','/api/bootstrap',undefined,workshop)).data;
 assert.equal(bootstrap.notificationUnreadCount,1);
 assert.equal(bootstrap.notificationInbox[0].type,'connection-request');
 assert.equal((await call('POST','/api/notification-inbox/read-all',{},workshop)).status,200);
 assert.equal((await inbox(workshop)).data.unreadCount,0);
 // Only the addressed shop can approve, producing a rider event.
 assert.equal((await call('PATCH','/api/connections/'+req.data.id,{status:'accepted'},workshop)).status,200);
 let riderEvents=(await inbox(rider)).data;
 assert.equal(riderEvents.unreadCount,1);
 assert.equal(riderEvents.notifications[0].type,'connection-decision');
 assert.equal(riderEvents.notifications[0].route,'/rider/connections');
 assert.equal((await inbox(other)).data.notifications.length,0);
 assert.equal((await inbox(workshop)).data.unreadCount,0);
 // Event targets are generated by the server, never from untrusted request payload.
 const date=shift(3);
 const booking=await call('POST','/api/rider-appointments',{shopId,bikeId:bike.data.id,service:'Oil Change',date,time:'10:30'},rider);
 assert.equal(booking.status,201,JSON.stringify(booking.data));
 shopEvents=(await inbox(workshop)).data;
 assert.equal(shopEvents.notifications[0].type,'appointment-request');
 assert.equal(shopEvents.notifications[0].route,'/shop/appointments');
 assert.equal(shopEvents.unreadCount,1);
 assert.equal((await call('PATCH','/api/rider-appointments/'+booking.data.id,{status:'Confirmed'},workshop)).status,200);
 riderEvents=(await inbox(rider)).data;
 assert.equal(riderEvents.notifications[0].type,'appointment-update');
 assert.equal(riderEvents.notifications[0].route,'/rider/bookings');
 assert.equal(riderEvents.unreadCount,2);
 assert.equal((await call('GET','/api/notification-inbox',undefined,shop2)).data.unreadCount,0);
 // The confirmed booking can be completed only after its scheduled time.
 await pool.query('UPDATE rider_appointment_requests SET date=$1 WHERE id=$2',[shift(-2),booking.data.id]);
 assert.equal((await call('PATCH','/api/rider-appointments/'+booking.data.id,{status:'Completed'},workshop)).status,200);
 riderEvents=(await inbox(rider)).data;
 assert.equal(riderEvents.unreadCount,3);
 const report=await call('POST','/api/service-reports',{appointmentId:booking.data.id,service:'Engine Oil',serviceDate:shift(-1),cost:90,notes:'Oil replaced'},workshop);
 assert.equal(report.status,201,JSON.stringify(report.data));
 riderEvents=(await inbox(rider)).data;
 assert.equal(riderEvents.notifications[0].type,'service-report');
 assert.equal(riderEvents.notifications[0].route,'/rider/records');
 assert.equal((await call('PATCH','/api/service-reports/'+report.data.id,{decision:'Accepted'},rider)).status,200);
 shopEvents=(await inbox(workshop)).data;
 assert.equal(shopEvents.notifications[0].type,'report-decision');
 assert.equal(shopEvents.notifications[0].route,'/shop/records');
 const service=(await call('GET','/api/services',undefined,rider)).data.services[0];
 const share=await call('POST','/api/service-shares',{shopId,serviceId:service.id},rider);
 assert.equal(share.status,201);
 shopEvents=(await inbox(workshop)).data;
 assert.equal(shopEvents.notifications[0].type,'service-shared');
 assert.equal((await call('DELETE','/api/service-shares/'+share.data.id,undefined,rider)).status,200);
 shopEvents=(await inbox(workshop)).data;
 assert.equal(shopEvents.notifications[0].type,'share-revoked');
 // Dismissing a notification is scoped and irreversible for the dismissed row only.
 const toDismiss=shopEvents.notifications[0].id;
 assert.equal((await call('DELETE','/api/notification-inbox/'+toDismiss,undefined,rider)).status,404);
 assert.equal((await call('DELETE','/api/notification-inbox/'+toDismiss,undefined,workshop)).status,200);
 assert.equal((await call('DELETE','/api/notification-inbox/'+toDismiss,undefined,workshop)).status,404);
 assert.ok(!(await inbox(workshop)).data.notifications.some(x=>x.id===toDismiss));
 // Clearing one account cannot affect any other's unread badges.
 assert.equal((await call('POST','/api/notification-inbox/read-all',{},rider)).status,200);
 assert.equal((await inbox(rider)).data.unreadCount,0);
 assert.ok((await inbox(workshop)).data.unreadCount>0);
 assert.equal((await inbox(other)).data.notifications.length,0);
 assert.equal((await call('GET','/api/bootstrap',undefined,rider)).data.notificationUnreadCount,0);
 // Disconnect notifications are retained but sharing access is revoked.
 assert.equal((await call('DELETE','/api/connections/'+req.data.id,undefined,rider)).status,200);
 assert.equal((await inbox(workshop)).data.notifications[0].type,'connection-ended');
 assert.equal((await inbox(rider)).data.unreadCount,0,'Disconnect does not notify the actor');
 assert.equal((await call('GET','/api/notifications',undefined,rider)).status,200,'Legacy maintenance attention endpoint remains supported');
});
